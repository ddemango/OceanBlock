// Wraps dist-single/index.html into mobile/game-html.js so the app ships the game offline.
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync('dist-single/index.html', 'utf8')
  .replace(/<link rel="(manifest|icon|apple-touch-icon)"[^>]*>\s*/g, '');
writeFileSync('mobile/game-html.js', `// AUTO-GENERATED by \`npm run build:mobile\` — do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`mobile/game-html.js written (${(html.length / 1024).toFixed(0)} KB)`);
